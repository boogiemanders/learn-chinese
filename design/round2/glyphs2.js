// Hand-drawn square-block lettering in the weight of the Fujimidai Tunnel
// references: two-cell verticals, one-cell horizontals, small counters,
// loose square dots at stroke ends. Original drawings, our own characters.
// <span class="g2" data-text="出口" data-cell="10" data-color="#fff"></span>
const HAN = {
  '今': ['.....##.....', '....#..#....', '...#....#...', '##........##', '...######...', '............', '.##########.', '........##..', '.......##...', '......#.....'],
  '日': ['..########..', '..##....##..', '..##....##..', '..##....##..', '..########..', '..##....##..', '..##....##..', '..##....##..', '..########..', '..........#.'],
  '出': ['.....##.....', '##...##...##', '##...##...##', '############', '.....##.....', '##...##...##', '##...##...##', '##...##...##', '############', '#...........'],
  '口': ['............', '############', '##........##', '##........##', '##........##', '##........##', '##........##', '############', '..........##', '...........#'],
};
// Bold 5×5 caps (I is 3 wide), drawn to match.
const LAT = {
  A: ['.###.', '#...#', '#####', '#...#', '#...#'], D: ['####.', '#...#', '#...#', '#...#', '####.'],
  E: ['#####', '#....', '####.', '#....', '#####'], F: ['#####', '#....', '####.', '#....', '#....'],
  H: ['#...#', '#...#', '#####', '#...#', '#...#'], I: ['###', '.#.', '.#.', '.#.', '###'],
  L: ['#....', '#....', '#....', '#....', '#####'], M: ['#...#', '##.##', '#.#.#', '#...#', '#...#'],
  N: ['#...#', '##..#', '#.#.#', '#..##', '#...#'], O: ['.###.', '#...#', '#...#', '#...#', '.###.'],
  R: ['####.', '#...#', '####.', '#..#.', '#...#'], S: ['.####', '#....', '.###.', '....#', '####.'],
  T: ['#####', '..#..', '..#..', '..#..', '..#..'], U: ['#...#', '#...#', '#...#', '#...#', '.###.'],
  W: ['#...#', '#...#', '#.#.#', '##.##', '#...#'], Y: ['#...#', '.#.#.', '..#..', '..#..', '..#..'],
  '6': ['.###.', '#....', '####.', '#...#', '.###.'], '·': ['.', '.', '#', '.', '.'], ' ': ['..', '..', '..', '..', '..'],
  '▶': ['#..', '##.', '###', '##.', '#..'],
};
function drawG2(el) {
  const text = el.dataset.text, cell = Number(el.dataset.cell || 3), color = el.dataset.color || '#fff';
  let x0 = 0, rects = '', h = 0;
  for (const ch of text) {
    const map = HAN[ch] || LAT[ch.toUpperCase()] || LAT[' '];
    h = Math.max(h, map.length);
    map.forEach((row, y) => [...row].forEach((c, x) => {
      if (c === '#') rects += `<rect x="${(x0 + x) * cell}" y="${y * cell}" width="${cell}" height="${cell}"/>`;
    }));
    x0 += map[0].length + 1;
  }
  const w = (x0 - 1) * cell;
  el.innerHTML = `<svg role="img" aria-label="${text}" width="${w}" height="${h * cell}" viewBox="0 0 ${w} ${h * cell}" fill="${color}" shape-rendering="crispEdges" style="display:block">${rects}</svg>`;
}
window.addEventListener('DOMContentLoaded', () => document.querySelectorAll('.g2').forEach(drawG2));
