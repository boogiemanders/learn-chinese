def slug(t):
    return re.sub(r"[^a-z0-9]+", "", t.lower())[:16]

out = []
for t in TOPICS:
    words = []
    seen = set()
    for row in t["words"]:
        simp, trad, py, jp, meaning, *rest = row
        wid = f"tp-{t['id']}-{slug(py) or len(words)}"
        while wid in seen:
            wid += "x"
        seen.add(wid)
        w = dict(id=wid, simplified=simp, traditional=trad, pinyin=py, jyutping=jp,
                 meaning=meaning, deck="topic", topic=t["id"])
        if rest:
            w["note"] = rest[0]
        words.append(w)
    out.append({k: v for k, v in t.items() if k != "words"} | {"words": words})

here = os.path.dirname(os.path.abspath(__file__))
path = os.path.join(here, "..", "Shared", "topics.json")
with open(path, "w", encoding="utf-8") as f:
    json.dump(out, f, ensure_ascii=False, indent=1)
print(f"{len(out)} topics, {sum(len(t['words']) for t in out)} words -> {os.path.normpath(path)}")
